CREATE TABLE IF NOT EXISTS mes_work_order (
    work_order_id VARCHAR(64) PRIMARY KEY,
    line_code VARCHAR(64) NOT NULL,
    product_code VARCHAR(64) NOT NULL,
    shift_code VARCHAR(32) NOT NULL,
    planned_qty INTEGER NOT NULL,
    actual_qty INTEGER NOT NULL,
    defect_qty INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS qe_measurement (
    measurement_id VARCHAR(64) PRIMARY KEY,
    work_order_id VARCHAR(64) NOT NULL,
    station_code VARCHAR(64) NOT NULL,
    metric_code VARCHAR(64) NOT NULL,
    metric_value NUMERIC(12,4) NOT NULL,
    lower_limit NUMERIC(12,4) NOT NULL,
    upper_limit NUMERIC(12,4) NOT NULL,
    measured_at TIMESTAMPTZ NOT NULL
);

